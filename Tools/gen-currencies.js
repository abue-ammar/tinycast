#!/usr/bin/env node
// Generate Tinycast/Core/Calculator/CurrencyData.generated.swift from Frankfurter's currency list.
//
// Usage: node Tools/gen-currencies.js [currencies.json]
// Downloads the source when no path is given. Run occasionally, commit the output.
//
// Only the mechanical half lives here — ISO codes and display names, which the feed owns and which
// go stale by hand. The judgement calls stay in CalcCurrency.swift: natural-language aliases
// ("quid", "bucks"), the shorter badge labels, and the currency-sign tie-breaks the feed can't make
// (it lists "$" for eleven different currencies).
"use strict";

const fs = require("fs");
const path = require("path");

const SOURCE = "https://api.frankfurter.dev/v2/currencies";
// The feed serves ~165 live currencies; a collapse well below that means a bad response, not a real change.
const MIN_EXPECTED = 120;
// `scope` defaults to live currencies, so retirement filtering is only a backstop. Thin markets and
// weekends leave a real currency a few days stale (4 is the observed worst case), so the cutoff has
// to be generous — a genuinely retired code trails by years (ATS ended 2002, BGN 2025).
const MAX_STALE_DAYS = 90;

async function load(argPath) {
  if (argPath) return JSON.parse(fs.readFileSync(argPath, "utf8"));
  const response = await fetch(SOURCE);
  if (!response.ok) throw new Error(`${SOURCE} -> HTTP ${response.status}`);
  return response.json();
}

async function main() {
  const currencies = await load(process.argv[2]);
  if (!Array.isArray(currencies) || currencies.length === 0)
    throw new Error("expected a non-empty array of currencies");

  const latest = currencies.reduce((max, c) => (c.end_date > max ? c.end_date : max), "");
  const cutoff = new Date(Date.parse(latest) - MAX_STALE_DAYS * 86400_000)
    .toISOString()
    .slice(0, 10);
  const live = currencies
    .filter((c) => c.end_date >= cutoff)
    .sort((a, b) => a.iso_code.localeCompare(b.iso_code));

  const dropped = currencies.length - live.length;
  if (live.length < MIN_EXPECTED)
    throw new Error(`suspiciously few currencies: ${live.length}`);

  const rows = live.map((c) => {
    const code = c.iso_code;
    const name = c.name;
    if (!/^[A-Z]{3}$/.test(code)) throw new Error(`unexpected ISO code ${JSON.stringify(code)}`);
    if (!name || name.includes('"') || name.includes("\\"))
      throw new Error(`unsafe name for ${code}: ${JSON.stringify(name)}`);
    return `        ("${code}", "${name}"),`;
  });

  const out = path.resolve(
    __dirname,
    "..",
    "Tinycast/Core/Calculator/CurrencyData.generated.swift",
  );
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(
    out,
    "// Generated by Tools/gen-currencies.js — do not edit by hand.\n" +
      `// Live currencies from ${SOURCE}, as of ${latest}; retired codes are omitted.\n` +
      "enum CurrencyData {\n" +
      "    /// Every currency the rate feed still publishes, as (ISO 4217 code, display name).\n" +
      "    static let all: [(code: String, name: String)] = [\n" +
      `${rows.join("\n")}\n` +
      "    ]\n" +
      "}\n",
  );
  console.log(`wrote ${out} (${live.length} currencies as of ${latest}, ${dropped} retired)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
