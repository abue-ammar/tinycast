#!/bin/bash
# Vendor TinycastProtocol from tinycast-extensions at a tag into Features/Extensions/Model/Protocol/.
# Usage: ./Scripts/sync-extension-protocol.sh v1.0.0. The repo is private, so it clones over SSH.
set -euo pipefail
cd "$(dirname "$0")/.." || exit 1

tag="${1:-}"
if ! [[ "$tag" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "usage: $0 <tag>, such as v1.0.0" >&2
    exit 2
fi

remote="git@github.com:abue-ammar/tinycast-extensions.git"
destination="Tinycast/Features/Extensions/Model/Protocol"
scratch="$(mktemp -d)"
trap 'rm -rf "$scratch"' EXIT

git -c advice.detachedHead=false clone --quiet --depth 1 --branch "$tag" "$remote" "$scratch/repo"

mkdir -p "$destination"
rm -f "$destination"/*.generated.swift
for source in "$scratch/repo/Sources/TinycastProtocol"/*.swift; do
    name="$(basename "$source" .swift)"
    {
        echo "// Generated by Scripts/sync-extension-protocol.sh from tinycast-extensions $tag. Never edit."
        cat "$source"
    } > "$destination/$name.generated.swift"
done

echo "Vendored TinycastProtocol $tag into $destination. Run xcodegen generate if files were added."
